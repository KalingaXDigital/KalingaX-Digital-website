-- KalingaX Digital website lead form setup
-- Public visitors can submit inquiries. They cannot read, update, or delete rows.

create table if not exists public.customer_inquiries (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 100),
  phone text not null check (char_length(btrim(phone)) between 7 and 24),
  email text not null check (char_length(btrim(email)) between 3 and 254),
  service text not null check (char_length(btrim(service)) between 1 and 120),
  message text not null check (char_length(btrim(message)) between 1 and 2000),
  created_at timestamptz not null default now()
);

alter table public.customer_inquiries enable row level security;

-- Keep the public API limited to new inquiry submissions.
revoke all on table public.customer_inquiries from public, anon, authenticated;
grant usage on schema public to anon;
grant insert on table public.customer_inquiries to anon;

drop policy if exists "Public can submit customer inquiries" on public.customer_inquiries;
create policy "Public can submit customer inquiries"
on public.customer_inquiries
for insert
to anon
with check (true);
